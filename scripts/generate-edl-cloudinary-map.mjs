// Generates src/data/edl-cloudinary-map.ts — a static product code -> Cloudinary URL
// lookup for the EDL image folder.
//
// Why this exists: Cloudinary randomizes public_id on upload (e.g. edl/tmhnq9tnys8g1lgxsszk),
// so URLs can't be predicted from the product code. Cloudinary does keep the original
// upload filename in `display_name` though, so this script fetches every resource under
// edl/ via the Admin API and matches it back to a product by:
//   1. display_name containing the product code slug (e.g. "dms-2048xm-pearl-calacatta-matt")
//   2. display_name (batch prefix like "p063-" stripped) matching the design name slug
//   3. a shared 4-5 digit numeric code fragment, when unambiguous
//
// Run with: node scripts/generate-edl-cloudinary-map.mjs
// Requires CLOUDINARY_URL in .env.local (cloudinary://<key>:<secret>@<cloud_name>).

import { config } from 'dotenv';
import { readFileSync, writeFileSync } from 'fs';

config({ path: new URL('../.env.local', import.meta.url) });

const CLOUDINARY_URL = process.env.CLOUDINARY_URL;
if (!CLOUDINARY_URL) throw new Error('CLOUDINARY_URL not set in .env.local');
const parsed = CLOUDINARY_URL.match(/^cloudinary:\/\/([^:]+):([^@]+)@(.+)$/);
if (!parsed) throw new Error('Could not parse CLOUDINARY_URL');
const [, apiKey, apiSecret, cloudName] = parsed;
const auth = Buffer.from(`${apiKey}:${apiSecret}`).toString('base64');

async function fetchAllEdlResources() {
  let all = [];
  let cursor;
  do {
    const url = new URL(`https://api.cloudinary.com/v1_1/${cloudName}/resources/image/upload`);
    url.searchParams.set('prefix', 'edl/');
    url.searchParams.set('max_results', '500');
    if (cursor) url.searchParams.set('next_cursor', cursor);
    const res = await fetch(url, { headers: { Authorization: `Basic ${auth}` } });
    if (!res.ok) throw new Error(`Cloudinary API error ${res.status}: ${await res.text()}`);
    const page = await res.json();
    all = all.concat(page.resources);
    cursor = page.next_cursor;
  } while (cursor);
  return all;
}

function slugify(input) {
  return input
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/(^-|-$)+/g, '');
}

function numberKeys(code) {
  const matches = code.toLowerCase().match(/\d{4,5}/g) || [];
  const keys = [];
  for (const v of matches) {
    keys.push(v);
    if (v.length === 5 && v.startsWith('1')) keys.push(v.slice(1));
  }
  return keys;
}

function stripBatchPrefix(dn) {
  return dn.replace(/^p\d+-/, '');
}

function parseProducts(source) {
  const products = [];
  const objRegex = /\{\s*"slug":\s*"([^"]+)"[\s\S]*?"code":\s*"([^"]+)"[\s\S]*?"design":\s*"([^"]*)"/g;
  let m;
  while ((m = objRegex.exec(source))) {
    products.push({ slug: m[1], code: m[2], design: m[3] });
  }
  return products;
}

const resources = await fetchAllEdlResources();
console.log(`Fetched ${resources.length} resources from Cloudinary "edl/" folder.`);

const productsSrc = readFileSync(new URL('../src/data/edl-products-from-csv.ts', import.meta.url), 'utf-8');
const products = parseProducts(productsSrc);
console.log(`Parsed ${products.length} products.`);

const byNumber = new Map();
for (const r of resources) {
  const dn = (r.display_name || '').toLowerCase();
  for (const n of dn.match(/\d{4,5}/g) || []) {
    if (!byNumber.has(n)) byNumber.set(n, []);
    byNumber.get(n).push(r);
  }
}

const mapping = {};
let matched = 0;

for (const p of products) {
  const codeSlug = slugify(p.code);
  const designSlug = slugify(p.design || '');
  let resource = resources.find(r => (r.display_name || '').toLowerCase().includes(codeSlug));

  if (!resource && designSlug) {
    resource = resources.find(r => {
      const stripped = stripBatchPrefix((r.display_name || '').toLowerCase());
      return stripped === designSlug || stripped.startsWith(`${designSlug}-`);
    });
  }

  if (!resource) {
    for (const n of numberKeys(p.code)) {
      const candidates = byNumber.get(n);
      if (candidates && candidates.length === 1) {
        resource = candidates[0];
        break;
      }
    }
  }

  if (resource) {
    mapping[p.code] = resource.secure_url;
    matched++;
  }
}

console.log(`Matched ${matched} / ${products.length} products to a Cloudinary image.`);

const header = `// Auto-generated by scripts/generate-edl-cloudinary-map.mjs — do not edit manually.
// Maps EDL product code -> its actual Cloudinary secure_url, resolved against the
// "edl/" folder's display_name metadata (public_id itself is randomized by Cloudinary).
`;
const body = `${header}\nexport const edlCloudinaryMap: Record<string, string> = ${JSON.stringify(mapping, null, 2)};\n`;

writeFileSync(new URL('../src/data/edl-cloudinary-map.ts', import.meta.url), body);
console.log('Wrote src/data/edl-cloudinary-map.ts');
