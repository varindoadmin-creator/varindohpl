import fs from 'node:fs';
import path from 'node:path';

const inputPath = path.join(process.cwd(), 'public', 'data', 'edl-products.csv');
const outputPath = path.join(process.cwd(), 'src', 'data', 'edl-products-from-csv.ts');

function slugify(input) {
  return input
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)+/g, '');
}

function parseCsvLine(line) {
  const cells = [];
  let current = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    const next = line[i + 1];

    if (char === '"' && next === '"') {
      current += '"';
      i += 1;
      continue;
    }
    if (char === '"') {
      inQuotes = !inQuotes;
      continue;
    }
    if (char === ',' && !inQuotes) {
      cells.push(current.trim());
      current = '';
      continue;
    }
    current += char;
  }

  cells.push(current.trim());
  return cells;
}

function toBoolean(value) {
  return String(value).trim().toUpperCase() === 'TRUE';
}

function descriptionForCollection(collection, design) {
  switch (collection) {
    case 'Wood':    return `EDL ${design} — an authentic wood-inspired HPL surface for cabinetry, furniture, and wall panels.`;
    case 'Pattern': return `EDL ${design} — a decorative HPL surface for feature walls and distinctive interior panels.`;
    case 'Solid':   return `EDL ${design} — a versatile solid-colour HPL for clean modern interiors.`;
    case 'Stone':   return `EDL ${design} — a stone-effect HPL surface for premium interior applications.`;
    case 'Marble':  return `EDL ${design} — a marble-effect HPL for elegant and refined interior spaces.`;
    case 'Metal':   return `EDL ${design} — a metallic HPL surface for contemporary premium interior projects.`;
    case 'Aptico':  return `EDL ${design} — a premium Aptico HPL, made in Austria, for high-end interior specification.`;
    default:        return `EDL ${design} — a premium HPL decorative surface manufactured in Austria.`;
  }
}

if (!fs.existsSync(inputPath)) {
  console.error(`Missing ${inputPath}`);
  process.exit(1);
}

const content = fs.readFileSync(inputPath, 'utf8').trim();
const [headerLine, ...rows] = content.split(/\r?\n/);
const headers = parseCsvLine(headerLine).map((h) => h.trim());

// Expected headers:
// Item Name, Design Name, Code, New Arrivals, Best Sellers, Promo Items,
// Rate, Status, Usage unit, Unit, Size, Sub Collection, Collection, Thickness

const products = rows
  .map((line) => {
    const values = parseCsvLine(line);
    const r = Object.fromEntries(headers.map((h, i) => [h, values[i] || '']));

    const name       = r['Item Name']      || '';
    const code       = r['Design Name']    || '';  // SKU, e.g. "DA 2081N"
    const design     = r['Code']           || '';  // Pattern name, e.g. "TITAN I"
    const collection = r['Collection']     || '';  // Wood, Pattern, Solid, Stone, Marble, Metal, Aptico
    const category   = r['Sub Collection'] || '';  // e.g. Aspen, Fine Matt, Marble Matt
    const size       = r['Size']           || '';
    const thickness  = r['Thickness']      || '';
    const price      = Number.parseInt(r['Rate'], 10) || null;
    const active     = r['Status']?.trim().toLowerCase() === 'active';

    const isNew      = toBoolean(r['New Arrivals']);
    const isBest     = toBoolean(r['Best Sellers']);
    const isPromo    = toBoolean(r['Promo Items']);

    const badges = [];
    if (isNew)  badges.push('NEW');
    if (isBest) badges.push('BESTSELLER');
    if (isPromo) badges.push('PROMO');

    if (!code || !name) return null;

    return {
      slug: slugify(`${code} ${design || name}`),
      code,
      name,
      design,
      brand: 'EDL',
      collection,
      category,
      size,
      thickness,
      price,
      isPromoItem: isPromo || undefined,
      currency: 'IDR',
      active,
      badges,
      description: descriptionForCollection(collection, design || name),
    };
  })
  .filter(Boolean);

const output = `import type { Product } from '@/types/product';

// Auto-generated by scripts/import-edl-products-from-csv.mjs.
// Source: public/data/edl-products.csv — do not edit manually.
export const edlProductsFromCsv: Product[] = ${JSON.stringify(products, null, 2)};
`;

fs.writeFileSync(outputPath, output);
console.log(`Imported ${products.length} EDL products → ${outputPath}`);
